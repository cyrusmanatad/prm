<?php

namespace App\Console\Commands;

use App\Mail\BrandRequestOutcome;
use App\Mail\FollowUpNotice;
use App\Mail\OnboardingInvitation;
use App\Mail\OnboardingLifecycle;
use App\Mail\PartnerInvitation;
use App\Mail\ScheduledNotice;
use App\Models\User;
use Illuminate\Auth\Notifications\ResetPassword;
use Illuminate\Auth\Notifications\VerifyEmail;
use Illuminate\Console\Command;
use Illuminate\Mail\Mailable;
use Illuminate\Support\Facades\Mail;

/**
 * Renders one email with synthetic values and prints it. Local/testing only. It reads no records and
 * delivers nothing: Mailables pass through the in-memory array transport solely to build their MIME parts.
 */
class MailPreview extends Command
{
    protected $signature = 'mail:preview {type? : Email to render; omit to list the available types} {--text : Print the plain-text part instead of HTML}';

    protected $description = 'Print a synthetic rendering of a transactional email without sending it';

    public function handle(): int
    {
        if (! app()->environment(['local', 'testing'])) {
            $this->error('Email previews are available only in local and testing environments.');

            return self::FAILURE;
        }
        $samples = $this->samples();
        $type = $this->argument('type');
        if ($type === null) {
            $this->line(implode("\n", array_keys($samples)));

            return self::SUCCESS;
        }
        if (! isset($samples[$type])) {
            $this->error('Unknown email type. Run mail:preview without arguments to list the types.');

            return self::FAILURE;
        }
        $sample = $samples[$type]();
        if (! $sample instanceof Mailable) {
            if ($this->option('text')) {
                $this->error('The plain-text part of account notifications is generated by the framework at send time.');

                return self::FAILURE;
            }
            $this->output->write((string) $sample->render());

            return self::SUCCESS;
        }
        Mail::mailer('array')->to('recipient@example.test')->send($sample);
        $email = Mail::mailer('array')->getSymfonyTransport()->messages()->last()->getOriginalMessage();
        $body = $this->option('text') ? $email->getTextBody() : $email->getHtmlBody();
        if ($body === null) {
            $this->error('This email is plain text only. Use --text.');

            return self::FAILURE;
        }
        $this->output->write($body);

        return self::SUCCESS;
    }

    /** @return array<string, callable(): mixed> */
    private function samples(): array
    {
        $origin = rtrim(config('app.url'), '/');
        $id = '0193a5b2-7c1e-7a44-9f10-3b2a6c1d9e77';
        $capability = $origin.'/onboarding#token=synthetic-preview-token';
        $expires = '2026-11-25 08:00:00+00';
        $user = (new User)->forceFill(['id' => 1, 'name' => 'Preview Account', 'email' => 'recipient@example.test']);

        return [
            'partner-invitation' => fn () => new PartnerInvitation($origin.'/partnerships/accept#synthetic-preview-token', $expires, $id),
            'onboarding-invitation' => fn () => new OnboardingInvitation($capability, $expires, $id),
            'onboarding-submitted' => fn () => new OnboardingLifecycle('onboarding.submitted', $origin.'/partner/onboarding?request='.$id, $expires, $id),
            'onboarding-corrected' => fn () => new OnboardingLifecycle('onboarding.corrected', $capability, $expires, $id),
            'onboarding-accepted' => fn () => new OnboardingLifecycle('onboarding.accepted', $capability, $expires, $id),
            'brand-request-approved' => fn () => new BrandRequestOutcome('brand_request.approved', $origin.'/brand/requests/'.$id, $id),
            'brand-request-needs-information' => fn () => new BrandRequestOutcome('brand_request.needs_information', $origin.'/brand/requests/'.$id, $id),
            'brand-request-declined' => fn () => new BrandRequestOutcome('brand_request.declined', $origin.'/brand/requests/'.$id, $id),
            'schedule-reminder' => fn () => new ScheduledNotice('schedule.reminder', 'Asia/Manila', '2026-11-18 09:00 +08:00', $id, $id),
            'schedule-weekly-digest' => fn () => new ScheduledNotice('schedule.weekly_digest', 'Asia/Manila', '2026-11-18 09:00 +08:00', $id, $id, ['dueReminders' => 3, 'onboardingReviews' => 1]),
            'follow-up-review' => fn () => new FollowUpNotice(true, $id, '', '', 'owner@example.test'),
            'follow-up-approved' => fn () => new FollowUpNotice(false, $id, 'Synthetic subject', "Synthetic approved message.\nSecond line.", 'owner@example.test'),
            'password-reset' => fn () => (new ResetPassword('synthetic-preview-token'))->toMail($user),
            'verify-email' => fn () => (new VerifyEmail)->toMail($user),
        ];
    }
}
