import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { changeRole, fixture, login, migrationFixture, mutate, openPortalTool } from './helpers';

test('a Brand saves a private draft and shares the brief with its selected Partner', async ({ page }, info) => {
    const suffix = info.project.name + '-' + Date.now();
    const brand = 'm1-browser-campaign-brand-' + suffix + '@example.test';
    const partner = 'm1-browser-campaign-partner-' + suffix + '@example.test';
    fixture('seed', brand);
    fixture('seed', partner);
    const seed = JSON.parse(migrationFixture('lead-visibility-fixture.php', brand, partner, 'Winter Studio'));
    await login(page, brand);
    expect(await mutate(page, '/workspace/select', 'POST', { org_id: seed.brand })).toBe(200);
    await page.goto('/brand/home');
    await openPortalTool(page, 'Brand', 'Campaigns');
    await page.getByLabel('Campaign name').fill('Winter collection');
    await page.getByRole('button', { name: 'Create draft' }).click();
    await expect(page.getByRole('heading', { name: 'Winter collection' })).toBeVisible();
    await page.getByLabel('Brief', { exact: true }).fill('Photograph three pieces from the collection.');
    await page.getByLabel('Due date').fill('2027-02-03');
    await page.getByRole('button', { name: 'Save private draft' }).click();
    await expect(page.getByText('Draft saved.', { exact: true }).first()).toBeVisible();
    await page.reload();
    await expect(page.getByLabel('Due date')).toHaveValue('2027-02-03');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    if (process.env.CAPTURE_BROWSER_IMAGES === '1') await page.screenshot({ path: info.outputPath('draft.png') });
    await page.getByRole('combobox', { name: 'Share with Partner' }).click();
    await page.getByRole('option', { name: seed.partners[0].name }).click();
    await page.getByRole('button', { name: 'Share brief' }).click();
    await expect(page.getByText('Shared with ' + seed.partners[0].name)).toBeVisible();
    changeRole(brand, 'viewer');
    await page.goto('/brand/campaigns');
    await expect(page.getByRole('button', { name: 'Create draft' })).toHaveCount(0);
    expect(await mutate(page, '/brand/campaigns', 'POST', { title: 'Viewer draft' })).toBe(403);
    await page.context().clearCookies();
    await login(page, partner);
    expect(await mutate(page, '/workspace/select', 'POST', { org_id: seed.partners[0].org })).toBe(200);
    await page.goto('/partner/home');
    await openPortalTool(page, 'Partner', 'Campaigns');
    await page.getByRole('link', { name: 'Winter collection' }).click();
    await expect(page.getByText('Photograph three pieces from the collection.')).toBeVisible();
    await expect(page.getByText('Due date · Feb 3, 2027')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    if (process.env.CAPTURE_BROWSER_IMAGES === '1') await page.screenshot({ path: info.outputPath('brief.png') });
});
