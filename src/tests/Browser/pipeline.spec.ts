import AxeBuilder from '@axe-core/playwright';
import { test, expect } from '@playwright/test';
import { changeRole, fixture, login } from './helpers';

test('private pipeline capture, seven stages, stale tabs, snooze, activity, and deletion', async ({ page }, info) => {
    test.setTimeout(120_000);
    const email = `m1-browser-pipeline-${Date.now()}@example.test`;
    fixture('seed-workspaces', email);
    await login(page, email);
    await page.getByRole('button', { name: /Role test workspace/ }).click();
    await page.getByRole('link', { name: 'Open creator pipeline' }).click();
    await expect(page.getByText('Your pipeline is empty.', { exact: false })).toBeVisible();
    await page.getByText('Capture a lead', { exact: true }).click();
    await page.getByLabel('Brand name', { exact: true }).fill('M2 Studio');
    await page.getByLabel('Estimated value', { exact: true }).fill('1234.56');
    await page.getByLabel('Private notes (optional)').fill('Private creator notes');
    await page.getByRole('button', { name: 'Capture lead', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'M2 Studio', exact: true })).toBeVisible();
    await expect(page.getByRole('status')).toContainText('Lead captured.');
    await expect(page.getByRole('region', { name: 'Pipeline totals' })).toContainText('PHP 1,234.56');
    const leadUrl = page.url();
    for (const stage of ['pitched', 'negotiating', 'onboarded', 'active', 'repeat-client', 'lost', 'lead']) {
        await page.getByLabel('Stage', { exact: true }).selectOption(stage);
        await page.getByRole('button', { name: 'Move lead', exact: true }).click();
        await expect(page.getByRole('status')).toContainText('Stage updated.');
        await expect(page.getByRole('button', { name: 'Move lead', exact: true })).toBeEnabled();
        await page.reload();
        await expect(page.getByLabel('Stage', { exact: true })).toHaveValue(stage);
    }
    const stale = await page.context().newPage();
    await stale.goto(leadUrl);
    await stale.getByLabel('Brand name', { exact: true }).fill('Unsaved stale draft');
    await page.getByLabel('Brand name', { exact: true }).fill('Latest studio');
    await page.getByRole('button', { name: 'Save lead', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Lead saved.');
    await stale.getByRole('button', { name: 'Save lead', exact: true }).click();
    await expect(stale.getByRole('alert')).toContainText('changed in another session');
    await expect(stale.getByLabel('Brand name', { exact: true })).toHaveValue('Unsaved stale draft');
    await expect(stale.getByRole('button', { name: 'Save lead', exact: true })).toBeDisabled();
    await stale.getByRole('button', { name: 'Reload latest lead', exact: true }).click();
    await expect(stale.getByLabel('Brand name', { exact: true })).toHaveValue('Latest studio');
    await stale.close();
    await page.getByLabel('Private notes (optional)').fill('Draft kept across next-action and activity updates.');
    await page.getByLabel('Snooze until (your local time)').fill('2035-06-10T09:30');
    await page.getByRole('button', { name: 'Snooze next action', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Next action snoozed.');
    await page.getByLabel('Activity details').fill('Discussed the next collaboration.');
    await page.getByRole('button', { name: 'Record activity', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Activity recorded.');
    await expect(page.getByText('Discussed the next collaboration.', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Private notes (optional)')).toHaveValue('Draft kept across next-action and activity updates.');
    await page.getByRole('button', { name: 'Save lead', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Lead saved.');
    await expect(page.getByRole('button', { name: 'Save lead', exact: true })).toBeEnabled();
    await page.reload();
    await expect(page.getByLabel('Next action (optional, your local time)')).toHaveValue('2035-06-10T09:30');
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa', 'best-practice']).analyze();
    await info.attach('axe-pipeline', { body: JSON.stringify({ project: info.project.name, violations: scan.violations, incomplete: scan.incomplete }), contentType: 'application/json' });
    expect(scan.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) }))).toEqual([]);
    expect(await page.evaluate(() => document.body.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('pipeline-detail.png'), fullPage: true });
    await page.getByRole('link', { name: 'Close lead', exact: true }).click();
    await expect(page.getByRole('link', { name: 'Close lead', exact: true })).toHaveCount(0);
    await page.getByLabel('Due next actions only').check();
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
    await expect(page.getByText('No leads match these filters.', { exact: true })).toBeVisible();
    await page.goto(leadUrl);
    await page.getByText('Delete lead', { exact: true }).click();
    await page.getByLabel('I want to delete this lead', { exact: true }).check();
    await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Lead deleted.' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Latest studio', exact: true })).toHaveCount(0);
});

test('viewer reads private workspace pipeline and revocation blocks further page access', async ({ page }) => {
    const email = `m1-browser-pipeline-viewer-${Date.now()}@example.test`;
    fixture('seed-workspaces', email);
    await login(page, email);
    await page.getByRole('button', { name: /Role test workspace/ }).click();
    await page.getByRole('link', { name: 'Open creator pipeline' }).click();
    changeRole(email, 'viewer');
    await page.reload();
    await expect(page.getByText('Your viewer role provides read-only access to this pipeline.')).toBeVisible();
    await expect(page.getByText('Capture a lead', { exact: true })).toHaveCount(0);
    changeRole(email, 'revoked');
    const response = await page.reload();
    expect(response?.status()).toBe(403);
    await expect(page.getByRole('heading', { level: 1 })).toContainText('not available');
    await expect(page.getByText('Role test workspace', { exact: true })).toHaveCount(0);
});
